import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { config as loadEnv } from 'dotenv';

function main() {
  const rootDir = path.join(process.cwd(), '..');
  const envPath = fs.existsSync('.env') ? '.env' : path.join('..', '.env');
  loadEnv({ path: envPath });

  const target = process.argv[2] || 'local';
  const outputPath = path.join(
    process.cwd(),
    'wev-bulletin',
    'lib',
    'supabase',
    'database.types.ts'
  );

  let command = 'supabase gen types typescript --schema public';

  if (target === 'local') {
    command += ' --local';
  } else {
    // If staging/prod, we need the project ID
    let projectRef = process.env.SUPABASE_PROJECT_REF;

    if (!projectRef && process.env.SUPABASE_URL) {
      try {
        const urlObj = new URL(process.env.SUPABASE_URL);
        projectRef = urlObj.hostname.split('.')[0];
      } catch (e) {
        // ignore
      }
    }

    if (!projectRef || projectRef === 'localhost' || projectRef === '127') {
      console.error(
        '✗ Error: Valid SUPABASE_PROJECT_REF is required to generate remote types.',
      );
      process.exit(1);
    }
    
    command += ` --project-id "${projectRef}"`;
  }

  try {
    console.log(`▶ Generating types using command: ${command}`);
    const typesHeader = '// Generated from the Supabase public schema.\n// Regenerate with: npm run types:supabase\n// Do not edit this file by hand.\n\n';
    
    const output = execSync(command, { encoding: 'utf-8', stdio: 'pipe' });
    
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, typesHeader + output);
    console.log(`✓ Wrote ${outputPath}`);
  } catch (error: any) {
    console.error('❌ Failed to generate types.');
    if (error.stdout) console.error(error.stdout);
    if (error.stderr) console.error(error.stderr);
    process.exit(1);
  }
}

main();
