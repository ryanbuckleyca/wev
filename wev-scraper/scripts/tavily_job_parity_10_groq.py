def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--prod", action="store_true", help="Read from production DB")
    parser.add_argument("--delay", type=float, default=12.0)
    parser.add_argument(
        "--out-tag",
        default=None,
        help="Write scripts/tavily_job_parity_10_groq_<tag>.{md,json} (e.g. v2)",
    )
    parser.add_argument(
        "--only-job-ids",
        default=None,
        help="Comma-separated job IDs to run (subset of the fixed 10)",
    )
    args = parser.parse_args()
    if args.out_tag:
        _configure_report_paths(args.out_tag)

    reset_supabase_client_cache()

    priors = _load_gemini_priors()
    job_ids = list(priors.keys())
    if args.only_job_ids:
        wanted = {x.strip() for x in args.only_job_ids.split(",") if x.strip()}
        job_ids = [j for j in job_ids if j in wanted]
        missing = wanted - set(job_ids)
        if missing:
            logger.error("Unknown job ids (not in Gemini priors): %s", sorted(missing))
            raise SystemExit(2)
    if not args.only_job_ids and len(job_ids) != 10:
        logger.error("Expected 10 prior jobs, got %d from Gemini reports", len(job_ids))
        raise SystemExit(2)

    gemini_in_proc = bool((os.environ.get("GEMINI_API_KEY") or "").strip())
    cerebras_in_proc = bool((os.environ.get("CEREBRAS_API_KEY") or "").strip())
    google_search_on = _use_google_search_grounding()
    tavily_ok = is_tavily_available()

    probe = SSEFallbackProvider()
    chain_names = [n for n, _ in probe._providers]
    groq_only = chain_names == ["groq"]
    groq_first = bool(chain_names) and chain_names[0] == "groq"
    logger.info(
        "setup gemini_in_proc=%s (was=%s) cerebras_in_proc=%s (was=%s) "
        "google_search=%s tavily=%s chain=%s groq_only=%s",
        gemini_in_proc,
        _GEMINI_WAS_SET,
        cerebras_in_proc,
        _CEREBRAS_WAS_SET,
        google_search_on,
        tavily_ok,
        " → ".join(chain_names),
        groq_only,
    )
    if gemini_in_proc or any(n.startswith("gemini") for n in chain_names):
        logger.error("Gemini still available — aborting (want Groq-only)")
        raise SystemExit(2)
    if not groq_first:
        logger.error("Groq not first in chain: %s", chain_names)
        raise SystemExit(2)
    if not groq_only:
        logger.warning(
            "Chain is not groq-only (%s) — continuing but providers beyond groq may fire",
            chain_names,
        )

    try:
        require_tavily()
    except Exception as exc:
        logger.error("require_tavily failed: %s", exc)
        raise SystemExit(2) from exc

    try:
        clf = SSEClassifier()
    except SSEClassificationError as exc:
        logger.error("SSEClassifier init failed: %s", exc)
        raise SystemExit(2) from exc

    jobs = fetch_jobs_by_ids(job_ids)
    org_map = _org_type_map([j.get("organization_id") for j in jobs])
    logger.info("Selected %d fixed jobs for Groq/Tavily parity", len(jobs))

    reports: list[dict] = []
    failures: list[str] = []
    providers_used: list[str] = []

    for i, job in enumerate(jobs):
        if i:
            time.sleep(args.delay)
        jid = str(job["id"])
        prior = priors[jid]
        org_info = org_map.get(job.get("organization_id")) or {}
        details = _parse_details(job.get("sse_details"))
        prod = {
            "sse_rating": job.get("sse_rating"),
            "is_sse": job.get("is_sse"),
            "org_type": org_info.get("type") or prior.get("prod_org_type"),
            "baseline_quality": prior.get("baseline_quality"),
            "reasoning": details.get("reasoning"),
        }
        # Prefer live prod; fall back to prior snapshot if somehow null
        if prod["sse_rating"] is None:
            prod["sse_rating"] = prior.get("prod_sse_rating")
        if prod["is_sse"] is None:
            prod["is_sse"] = prior.get("prod_is_sse")

        gemini = {
            "sse_rating": prior.get("gemini_sse_rating"),
            "is_sse": prior.get("gemini_is_sse"),
            "provider": prior.get("gemini_provider"),
            "confidence": prior.get("gemini_confidence"),
            "reasoning": prior.get("gemini_reasoning"),
            "tavily_hosts": prior.get("gemini_tavily_hosts"),
            "divergence_label": prior.get("gemini_divergence_label"),
        }

        logger.info(
            "=== JOB %d/%d [%s] %s @ %s (prod=%s gemini=%s) ===",
            i + 1,
            len(jobs),
            prior.get("batch"),
            job.get("job_title"),
            job.get("organization"),
            prod.get("sse_rating"),
            gemini.get("sse_rating"),
        )
        try:
            rerun = classify_job_tavily_always(clf, job)
        except Exception as exc:
            logger.error("Unhandled: %s\n%s", exc, traceback.format_exc())
            rerun = {
                "error": str(exc),
                "elapsed_s": None,
                "tavily_always": True,
                "type": None,
            }
            failures.append(f"job {jid}: {exc}")

        if rerun.get("error"):
            err = str(rerun["error"])
            failures.append(f"job {jid}: {err}")
            if "429" in err or "quota" in err.lower() or "rate" in err.lower():
                failures.append(f"likely rate-limit/429 on job {jid}")
                time.sleep(15)

        if rerun.get("provider"):
            providers_used.append(str(rerun["provider"]))
            if str(rerun["provider"]).startswith("gemini"):
                failures.append(
                    f"UNEXPECTED gemini provider on job {jid}: {rerun['provider']}"
                )

        rating_gp = (not rerun.get("error")) and (
            prod.get("sse_rating") == rerun.get("sse_rating")
        )
        is_sse_gp = (not rerun.get("error")) and (
            prod.get("is_sse") == rerun.get("is_sse")
        )
        rating_gg = (not rerun.get("error")) and (
            gemini.get("sse_rating") == rerun.get("sse_rating")
        )
        is_sse_gg = (not rerun.get("error")) and (
            gemini.get("is_sse") == rerun.get("is_sse")
        )
        rating_gmp = prod.get("sse_rating") == gemini.get("sse_rating")
        is_sse_gmp = prod.get("is_sse") == gemini.get("is_sse")

        flags = {
            "groq_vs_prod_rating": rating_gp,
            "groq_vs_prod_is_sse": is_sse_gp,
            "groq_vs_prod": rating_gp and is_sse_gp,
            "groq_vs_gemini_rating": rating_gg,
            "groq_vs_gemini_is_sse": is_sse_gg,
            "groq_vs_gemini": rating_gg and is_sse_gg,
            "gemini_vs_prod_rating": rating_gmp,
            "gemini_vs_prod_is_sse": is_sse_gmp,
            "gemini_vs_prod": rating_gmp and is_sse_gmp,
        }

        logger.info(
            "  groq rating=%s is_sse=%s provider=%s elapsed=%ss "
            "gr↔prod=%s gr↔gem=%s",
            rerun.get("sse_rating"),
            rerun.get("is_sse"),
            rerun.get("provider"),
            rerun.get("elapsed_s"),
            flags["groq_vs_prod"],
            flags["groq_vs_gemini"],
        )

        reports.append(
            {
                "job_id": jid,
                "batch": prior.get("batch"),
                "title": job.get("job_title") or prior.get("title"),
                "organization": job.get("organization") or prior.get("organization"),
                "prod": prod,
                "gemini": gemini,
                "rerun": rerun,
                "match_flags": flags,
            }
        )

    n = len(reports)
    ok = [r for r in reports if not (r.get("rerun") or {}).get("error")]

    groq_vs_prod_rating = _match_rates(
        [
            ((r.get("prod") or {}).get("sse_rating"), (r.get("rerun") or {}).get("sse_rating"))
            for r in ok
        ]
    )
    groq_vs_prod_is_sse = _match_rates(
        [
            ((r.get("prod") or {}).get("is_sse"), (r.get("rerun") or {}).get("is_sse"))
            for r in ok
        ]
    )
    groq_vs_prod_both = _match_rates(
        [
            (
                (
                    (r.get("prod") or {}).get("sse_rating"),
                    (r.get("prod") or {}).get("is_sse"),
                ),
                (
                    (r.get("rerun") or {}).get("sse_rating"),
                    (r.get("rerun") or {}).get("is_sse"),
                ),
            )
            for r in ok
        ]
    )

    groq_vs_gem_rating = _match_rates(
        [
            (
                (r.get("gemini") or {}).get("sse_rating"),
                (r.get("rerun") or {}).get("sse_rating"),
            )
            for r in ok
        ]
    )
    groq_vs_gem_is_sse = _match_rates(
        [
            ((r.get("gemini") or {}).get("is_sse"), (r.get("rerun") or {}).get("is_sse"))
            for r in ok
        ]
    )
    groq_vs_gem_both = _match_rates(
        [
            (
                (
                    (r.get("gemini") or {}).get("sse_rating"),
                    (r.get("gemini") or {}).get("is_sse"),
                ),
                (
                    (r.get("rerun") or {}).get("sse_rating"),
                    (r.get("rerun") or {}).get("is_sse"),
                ),
            )
            for r in ok
        ]
    )

    # Gemini vs prod from priors (all 10, independent of groq success)
    gem_vs_prod_rating = _match_rates(
        [
            (
                (r.get("prod") or {}).get("sse_rating"),
                (r.get("gemini") or {}).get("sse_rating"),
            )
            for r in reports
        ]
    )
    gem_vs_prod_is_sse = _match_rates(
        [
            ((r.get("prod") or {}).get("is_sse"), (r.get("gemini") or {}).get("is_sse"))
            for r in reports
        ]
    )
    gem_vs_prod_both = _match_rates(
        [
            (
                (
                    (r.get("prod") or {}).get("sse_rating"),
                    (r.get("prod") or {}).get("is_sse"),
                ),
                (
                    (r.get("gemini") or {}).get("sse_rating"),
                    (r.get("gemini") or {}).get("is_sse"),
                ),
            )
            for r in reports
        ]
    )

    match_rates = {
        "n": n,
        "n_ok": len(ok),
        "groq_vs_prod": {
            "sse_rating": groq_vs_prod_rating,
            "is_sse": groq_vs_prod_is_sse,
            "both": groq_vs_prod_both,
        },
        "groq_vs_gemini": {
            "sse_rating": groq_vs_gem_rating,
            "is_sse": groq_vs_gem_is_sse,
            "both": groq_vs_gem_both,
        },
        "gemini_vs_prod": {
            "sse_rating": gem_vs_prod_rating,
            "is_sse": gem_vs_prod_is_sse,
            "both": gem_vs_prod_both,
        },
    }

    notable_flips: list[str] = []
    for r in reports:
        groq = r.get("rerun") or {}
        gem = r.get("gemini") or {}
        prod = r.get("prod") or {}
        flags = r.get("match_flags") or {}
        title = r.get("title") or r.get("job_id")
        if groq.get("error"):
            notable_flips.append(f"**error** — {title}: {groq['error']}")
            continue
        if not flags.get("groq_vs_gemini"):
            notable_flips.append(
                f"**groq≠gemini** — {title} @ {r.get('organization')}: "
                f"gemini=`{gem.get('sse_rating')}`/{gem.get('is_sse')} → "
                f"groq=`{groq.get('sse_rating')}`/{groq.get('is_sse')} "
                f"(prod=`{prod.get('sse_rating')}`/{prod.get('is_sse')})"
            )
        elif not flags.get("groq_vs_prod") and flags.get("gemini_vs_prod"):
            notable_flips.append(
                f"**groq breaks gemini↔prod agree** — {title}: "
                f"prod=`{prod.get('sse_rating')}` → groq=`{groq.get('sse_rating')}`"
            )
        elif flags.get("groq_vs_prod") and not flags.get("gemini_vs_prod"):
            notable_flips.append(
                f"**groq recovers vs prod where gemini differed** — {title}: "
                f"prod=`{prod.get('sse_rating')}` gemini=`{gem.get('sse_rating')}` "
                f"groq=`{groq.get('sse_rating')}`"
            )

    groq_successes = sum(
        1
        for r in reports
        if str((r.get("rerun") or {}).get("provider") or "") == "groq"
    )
    erred = sum(1 for r in reports if (r.get("rerun") or {}).get("error"))

    # Consistency verdict
    g_rating = int(gem_vs_prod_rating["matches"])
    gr_rating = int(groq_vs_prod_rating["matches"])
    gr_gem = int(groq_vs_gem_rating["matches"])
    if gr_gem >= 8 and abs(gr_rating - g_rating) <= 1:
        consistency = (
            "Yes — Groq+Tavily is about as consistent as Gemini+Tavily: "
            f"high agreement with Gemini ({groq_vs_gem_both['frac']} both) and "
            f"similar prod rating match ({groq_vs_prod_rating['frac']} vs Gemini's "
            f"{gem_vs_prod_rating['frac']})."
        )
    elif gr_gem >= 7:
        consistency = (
            "Mostly — Groq largely tracks Gemini "
            f"({groq_vs_gem_rating['frac']} rating) but diverges on a few jobs; "
            f"prod rating match {groq_vs_prod_rating['frac']} vs Gemini "
            f"{gem_vs_prod_rating['frac']}."
        )
    else:
        consistency = (
            "No — Groq and Gemini disagree on too many ratings "
            f"({groq_vs_gem_rating['frac']}); treat Groq+Tavily as less interchangeable "
            "with Gemini+Tavily on this set."
        )

    verdict = (
        f"{consistency} "
        f"Groq completions: {groq_successes}/{n}; errors: {erred}. "
        f"Providers used: {providers_used}."
    )
    headline = (
        f"Groq↔prod rating **{groq_vs_prod_rating['frac']}** · "
        f"Groq↔Gemini rating **{groq_vs_gem_rating['frac']}** · "
        f"Gemini↔prod rating **{gem_vs_prod_rating['frac']}** (prior 6/10)."
    )

    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "mode": "tavily_always_force_grounding_groq_only",
        "dry_run": True,
        "wrote_to_db": False,
        "setup": {
            "gemini_key_in_process": gemini_in_proc,
            "gemini_was_in_env": _GEMINI_WAS_SET,
            "cerebras_key_in_process": cerebras_in_proc,
            "cerebras_was_in_env": _CEREBRAS_WAS_SET,
            "use_google_search_grounding": google_search_on,
            "tavily_available": tavily_ok,
            "provider_chain": " → ".join(chain_names),
            "groq_only": groq_only,
            "groq_first": groq_first,
            "out_tag": args.out_tag,
        },
        "job_ids": job_ids,
        "headline": headline,
        "match_rates": match_rates,
        "verdict": verdict,
        "notable_flips": notable_flips,
        "providers_used": providers_used,
        "failures": failures,
        "jobs": reports,
    }
    write_report(payload)
    print("\n======== HEADLINE ========")
    print(headline)
    print("\n======== VERDICT ========")
    print(verdict)
    print("\n======== MATCH RATES ========")
    print(json.dumps(match_rates, indent=2))
    print(f"\nReport: {REPORT_MD}")
    print(f"JSON:   {REPORT_JSON}")
    print(f"Log:    {LOG_PATH}")


if __name__ == "__main__":
    main()
