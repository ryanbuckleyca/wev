def _parse_details(raw: Any) -> dict:
    if isinstance(raw, dict):
        return raw
    if isinstance(raw, str) and raw.strip():
        try:
            parsed = json.loads(raw)
            return parsed if isinstance(parsed, dict) else {}
        except json.JSONDecodeError:
            return {"raw": raw}
    return {}


def _host(url: str) -> str | None:
    try:
        host = urlparse(url).netloc.lower()
    except Exception:
        return None
    if host.startswith("www."):
        host = host[4:]
    return host or None


def _yesno(v: Any) -> str:
    if v is True:
        return "yes"
    if v is False:
        return "NO"
    return "—"


def _load_gemini_priors() -> dict[str, dict[str, Any]]:
    """job_id -> {batch, title, org, prod_*, gemini_*} from prior reports."""
    out: dict[str, dict[str, Any]] = {}
    for path, batch in ((GEMINI_A_JSON, "A"), (GEMINI_B_JSON, "B")):
        if not path.is_file():
            raise FileNotFoundError(f"Missing prior Gemini report: {path}")
        data = json.loads(path.read_text())
        for row in data.get("jobs") or []:
            jid = row.get("job_id")
            if not jid:
                continue
            prod = row.get("prod") or {}
            rerun = row.get("rerun") or {}
            out[str(jid)] = {
                "batch": batch,
                "title": row.get("title") or prod.get("job_title"),
                "organization": row.get("organization") or prod.get("organization"),
                "prod_sse_rating": prod.get("sse_rating"),
                "prod_is_sse": prod.get("is_sse"),
                "prod_org_type": prod.get("type"),
                "gemini_sse_rating": rerun.get("sse_rating"),
                "gemini_is_sse": rerun.get("is_sse"),
                "gemini_provider": rerun.get("provider"),
                "gemini_confidence": rerun.get("confidence"),
                "gemini_reasoning": rerun.get("reasoning"),
                "gemini_tavily_hosts": rerun.get("tavily_hosts") or [],
                "gemini_divergence_label": row.get("divergence_label"),
                "baseline_quality": (prod.get("baseline_quality") or {}).get("quality"),
            }
    return out


def fetch_jobs_by_ids(job_ids: list[str]) -> list[dict]:
    rows = (
        supabase.table("jobs")
        .select(JOB_SELECT)
        .in_("id", job_ids)
        .execute()
        .data
        or []
    )
    by_id = {str(r["id"]): r for r in rows}
    missing = [jid for jid in job_ids if jid not in by_id]
    if missing:
        raise RuntimeError(f"Jobs not found in prod: {missing}")
    # Preserve prior report order (A then B)
    return [by_id[jid] for jid in job_ids]


def _org_type_map(org_ids: list[Any]) -> dict[Any, dict]:
    ids = [i for i in org_ids if i is not None]
    if not ids:
        return {}
    rows = (
        supabase.table("organizations")
        .select("id,name,type,sse_rating,is_sse")
        .in_("id", ids)
        .execute()
        .data
        or []
    )
    return {r["id"]: r for r in rows}


def classify_job_tavily_always(clf: SSEClassifier, job: dict) -> dict[str, Any]:
    org_name = job.get("organization") or "Unknown"
    job_title = job.get("job_title") or "Unknown"
    location = job.get("location") or "Unknown"
    salary = job.get("wage") or "Not specified"
    description = (job.get("description") or "").strip()
    posted_date = str(job.get("date_posted") or datetime.now(timezone.utc).isoformat())
    listing_url = job.get("listing_url") or ""

    if not description:
        raise SSEClassificationError("Job description required for parity re-run")

    prompt = get_sse_classification_prompt(
        org_name=org_name,
        job_title=job_title,
        location=location,
        salary=salary,
        job_description=description,
        posted_date=posted_date,
    )

    search_terms = f'"{org_name}"'
    if location and location != "Unknown":
        search_terms += f' "{location}"'
    search_query = f"{search_terms} official website mission governance"
    require_terms = entity_require_terms(org_name) or None

    evidence = fetch_tavily_evidence(search_query, require_terms=require_terms)
    tavily_urls = list(evidence.urls or [])
    tavily_hosts = sorted({h for u in tavily_urls if (h := _host(u))})

    t0 = time.perf_counter()
    last_error = ""
    for attempt in range(2):
        try:
            response_text = clf._call_provider_with_retry(
                provider=clf.provider,
                prompt=prompt,
                system=SSE_JOB_SYSTEM_PROMPT,
                task="sse",
                temperature=0,
                search_query=search_query,
                retries=0,
                require_terms=require_terms,
                use_grounding=True,  # tavily-always
            )
        except SSEClassificationError as exc:
            last_error = str(exc)
            logger.warning("provider error attempt %d/2: %s", attempt + 1, last_error)
            if "429" in last_error or "quota" in last_error.lower():
                time.sleep(8)
            continue

        parsed, parse_error = clf._safe_parse_sse_response(
            response_text, job_title, org_name
        )
        if parsed is not None:
            parsed = apply_job_sse_guards(
                parsed,
                salary=salary,
                description=description,
            )
            rating = parsed["rating"]
            provider_name = getattr(clf.provider, "current_model", None) or getattr(
                clf.provider, "_last_successful", None
            )
            return {
                "sse_rating": rating,
                "is_sse": rating in ("strong_yes", "weak_yes"),
                "type": None,
                "confidence": parsed.get("confidence"),
                "reasoning": parsed.get("reasoning"),
                "must_haves_met": parsed.get("must_haves_met") or [],
                "nice_to_haves_met": parsed.get("nice_to_haves_met") or [],
                "flags": parsed.get("flags") or [],
                "classified_at": parsed.get("classified_at"),
                "provider": provider_name,
                "listing_url": listing_url,
                "search_query": search_query,
                "tavily_always": True,
                "tavily_urls": tavily_urls,
                "tavily_hosts": tavily_hosts,
                "tavily_evidence_chars": len(evidence.text or ""),
                "elapsed_s": round(time.perf_counter() - t0, 2),
                "error": None,
            }
        last_error = parse_error or "parse error"
        logger.warning("parse error attempt %d/2: %s", attempt + 1, last_error)

    return {
        "error": last_error or "classification failed",
        "elapsed_s": round(time.perf_counter() - t0, 2),
        "tavily_always": True,
        "tavily_urls": tavily_urls,
        "tavily_hosts": tavily_hosts,
        "tavily_evidence_chars": len(evidence.text or ""),
        "type": None,
    }


def _match_rates(pairs: list[tuple[Any, Any]]) -> dict[str, Any]:
    n = len(pairs)
    m = sum(1 for a, b in pairs if a == b and a is not None)
    return {
        "n": n,
        "matches": m,
        "pct": f"{(100.0 * m / n):.0f}" if n else "0",
        "frac": f"{m}/{n}",
    }


