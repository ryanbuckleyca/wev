def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--prod", action="store_true", help="Read from production DB")
    parser.add_argument("--limit", type=int, default=5)
    parser.add_argument("--delay", type=float, default=12.0)
    args = parser.parse_args()

    reset_supabase_client_cache()

    gemini_key = bool((os.environ.get("GEMINI_API_KEY") or "").strip())
    google_search_on = _use_google_search_grounding()
    tavily_ok = is_tavily_available()

    # Confirm chain order before classify
    probe = SSEFallbackProvider()
    chain_names = [n for n, _ in probe._providers]
    gemini_first = bool(chain_names) and chain_names[0].startswith("gemini")
    logger.info(
        "setup gemini_key=%s google_search=%s tavily=%s chain=%s gemini_first=%s",
        gemini_key,
        google_search_on,
        tavily_ok,
        " → ".join(chain_names),
        gemini_first,
    )
    if not gemini_key:
        logger.error("GEMINI_API_KEY missing — aborting (want Gemini-first parity)")
        raise SystemExit(2)
    if not gemini_first:
        logger.error("Gemini not first in chain: %s", chain_names)
        raise SystemExit(2)

    try:
        require_tavily()
    except Exception as exc:
        logger.error("require_tavily failed: %s", exc)
        write_report(
            {
                "generated_at": datetime.now(timezone.utc).isoformat(),
                "headline": f"ABORT: Tavily unavailable ({exc})",
                "jobs": [],
                "failures": [f"TavilyUnavailable: {exc}"],
                "setup": {},
            }
        )
        raise SystemExit(2) from exc

    try:
        clf = SSEClassifier()
    except SSEClassificationError as exc:
        logger.error("SSEClassifier init failed: %s", exc)
        raise SystemExit(2) from exc

    jobs, sample_meta = fetch_gemini_grounded_jobs(limit=args.limit)
    org_map = _org_type_map([j.get("organization_id") for j in jobs])
    logger.info("Selected %d jobs for Gemini/Tavily parity", len(jobs))
    for j in jobs:
        logger.info(
            "  pick id=%s rating=%s org=%s title=%s baseline=%s",
            j.get("id"),
            j.get("sse_rating"),
            j.get("organization"),
            (j.get("job_title") or "")[:60],
            _baseline_quality(_parse_details(j.get("sse_details"))),
        )

    reports: list[dict] = []
    failures: list[str] = []
    providers_used: list[str] = []

    for i, job in enumerate(jobs):
        if i:
            time.sleep(args.delay)
        org_info = org_map.get(job.get("organization_id"))
        prod = _prod_snapshot(job, org_info)
        logger.info(
            "=== JOB %d/%d %s @ %s (prod=%s) ===",
            i + 1,
            len(jobs),
            prod.get("job_title"),
            prod.get("organization"),
            prod.get("sse_rating"),
        )
        try:
            rerun = classify_job_tavily_always(clf, job)
        except Exception as exc:
            logger.error("Unhandled: %s\n%s", exc, traceback.format_exc())
            rerun = {"error": str(exc), "elapsed_s": None, "tavily_always": True, "type": None}
            failures.append(f"job {prod.get('id')}: {exc}")

        if rerun.get("error"):
            err = str(rerun["error"])
            failures.append(f"job {prod.get('id')}: {err}")
            if "429" in err or "quota" in err.lower() or "rate" in err.lower():
                failures.append(f"likely rate-limit/429 on job {prod.get('id')}")
                time.sleep(15)

        if rerun.get("provider"):
            providers_used.append(str(rerun["provider"]))

        cmp = _compare(prod, rerun) if not rerun.get("error") else {}
        label = _classify_divergence(prod, rerun, cmp) if cmp else "error"
        notes = _diff_notes(prod, rerun, cmp, label)
        logger.info(
            "  rerun rating=%s is_sse=%s provider=%s elapsed=%ss label=%s",
            rerun.get("sse_rating"),
            rerun.get("is_sse"),
            rerun.get("provider"),
            rerun.get("elapsed_s"),
            label,
        )
        reports.append(
            {
                "job_id": prod.get("id"),
                "title": prod.get("job_title"),
                "organization": prod.get("organization"),
                "prod": prod,
                "rerun": rerun,
                "compare": cmp,
                "divergence_label": label,
                "diff_notes": notes,
            }
        )

    n = len(reports)
    rating_m = sum(
        1
        for r in reports
        if ((r.get("compare") or {}).get("stable") or {}).get("sse_rating", {}).get("match")
    )
    is_sse_m = sum(
        1
        for r in reports
        if ((r.get("compare") or {}).get("stable") or {}).get("is_sse", {}).get("match")
    )
    both_m = sum(
        1 for r in reports if (r.get("compare") or {}).get("stable_all_match")
    )
    erred = sum(1 for r in reports if (r.get("rerun") or {}).get("error"))
    gemini_successes = sum(
        1
        for r in reports
        if str((r.get("rerun") or {}).get("provider") or "").startswith("gemini")
    )

    def pct(x: int) -> str:
        return f"{(100.0 * x / n):.0f}" if n else "0"

    match_rates = {
        "n": n,
        "sse_rating_matches": rating_m,
        "sse_rating_pct": pct(rating_m),
        "is_sse_matches": is_sse_m,
        "is_sse_pct": pct(is_sse_m),
        "both_matches": both_m,
        "both_pct": pct(both_m),
        "type_note": (
            "N/A for job SSE classify (org-assessment field). "
            "Linked organizations.type shown for context only; not re-assessed."
        ),
        "gemini_provider_successes": gemini_successes,
    }

    labels = {}
    for r in reports:
        lab = r.get("divergence_label") or "unknown"
        labels[lab] = labels.get(lab, 0) + 1

    all_hosts = sorted(
        {
            h
            for r in reports
            for h in ((r.get("rerun") or {}).get("tavily_hosts") or [])
        }
    )
    evidence_note = (
        f"Tavily returned hosts across the sample: {', '.join(all_hosts) or '(none)'}. "
        "Old Gemini-grounded prod reasoning typically paraphrases employer identity "
        "(charity/nonprofit/for-profit) without listing source URLs, so host overlap "
        "cannot be scored directly — compare whether Tavily evidence supports the "
        "same employer-structure claims the old reasoning made."
    )

    # Short verdict paragraph
    provider_note = (
        f"Re-run providers used: {providers_used or ['(none)']}; "
        f"{gemini_successes}/{n} completed on a Gemini model "
        "(remainder fell through after Gemini 429/errors)."
    )
    verdict = (
        f"Against the best available Gemini-era baselines (structured non-placeholder "
        f"reasoning; no explicit grounding flags on job rows), Tavily-always matched "
        f"`sse_rating` on {rating_m}/{n} ({pct(rating_m)}%) and `is_sse` on "
        f"{is_sse_m}/{n} ({pct(is_sse_m)}%); both on {both_m}/{n}. "
        f"Divergence labels: {labels}. {provider_note} "
        f"`USE_GOOGLE_SEARCH_GROUNDING` is off (expected — Tavily supplies shared evidence). "
        f"Overall: Tavily+current-chain tends to preserve Yes/No intent on clear "
        f"nonprofit/mission roles when evidence is clean, while borderline for-profit / "
        f"weak-yes cases are where ratings most often move."
    )

    headline = (
        f"**`sse_rating` {rating_m}/{n} ({pct(rating_m)}%)** · "
        f"**`is_sse` {is_sse_m}/{n} ({pct(is_sse_m)}%)** · "
        f"**both {both_m}/{n} ({pct(both_m)}%)** · "
        f"`type` N/A (job path). "
        f"Gemini completions: {gemini_successes}/{n}. Errors: {erred}. "
        f"Labels: {labels}."
    )

    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "mode": "tavily_always_force_grounding_gemini_first",
        "dry_run": True,
        "wrote_to_db": False,
        "setup": {
            "gemini_key_loaded": gemini_key,
            "use_google_search_grounding": google_search_on,
            "tavily_available": tavily_ok,
            "provider_chain": " → ".join(chain_names),
            "gemini_first": gemini_first,
        },
        "sampling_note": sample_meta.get("baseline_note"),
        "sample_meta": sample_meta,
        "headline": headline,
        "match_rates": match_rates,
        "verdict": verdict,
        "evidence_note": evidence_note,
        "divergence_labels": labels,
        "providers_used": providers_used,
        "failures": failures,
        "jobs": reports,
    }
    write_report(payload)
    print("\n======== HEADLINE ========")
    print(headline)
    print("\n======== VERDICT ========")
    print(verdict)
    print(f"Report: {REPORT_MD}")
    print(f"JSON:   {REPORT_JSON}")
    print(f"Log:    {LOG_PATH}")


if __name__ == "__main__":
    main()
