def _compare(prod: dict, rerun: dict) -> dict[str, Any]:
    out: dict[str, Any] = {
        "stable": {},
        "narrative": {},
        "stable_all_match": True,
        "type": {
            "note": (
                "Job SSE classify does not emit `type` (org-assessment field). "
                "Prod value below is linked organizations.type for context only."
            ),
            "prod_org_type": prod.get("type"),
            "rerun_type": rerun.get("type"),
            "match": None,
        },
    }
    for f in STABLE_FIELDS:
        pv, rv = prod.get(f), rerun.get(f)
        match = pv == rv
        out["stable"][f] = {"match": match, "prod": pv, "rerun": rv}
        if not match:
            out["stable_all_match"] = False

    details = prod.get("sse_details") or {}
    for f in NARRATIVE_FIELDS:
        pv = details.get(f) if isinstance(details, dict) else None
        rv = rerun.get(f)
        if f in ("must_haves_met", "nice_to_haves_met", "flags"):
            ps = set(pv or []) if isinstance(pv, list) else set()
            rs = set(rv or []) if isinstance(rv, list) else set()
            out["narrative"][f] = {
                "exact_match": pv == rv,
                "overlap": sorted(ps & rs),
                "prod_only": sorted(ps - rs),
                "rerun_only": sorted(rs - ps),
                "prod": pv,
                "rerun": rv,
            }
        elif f == "confidence":
            try:
                diff = abs(float(pv or 0) - float(rv or 0))
            except (TypeError, ValueError):
                diff = None
            out["narrative"][f] = {
                "match": pv == rv,
                "abs_diff": diff,
                "prod": pv,
                "rerun": rv,
            }
        else:
            out["narrative"][f] = {
                "match": (pv or "") == (rv or ""),
                "prod": pv,
                "rerun": rv,
            }
    return out


def _md_escape(text: Any, limit: int = 600) -> str:
    s = str(text or "").replace("\n", " ").strip()
    if len(s) > limit:
        return s[: limit - 3] + "..."
    return s


def _cite_hosts_from_reasoning(text: str | None) -> list[str]:
    """Best-effort hosts / named sources mentioned in old Gemini reasoning."""
    if not text:
        return []
    found: list[str] = []
    for m in re.finditer(r"https?://([^\s)\]\"']+)", text, flags=re.I):
        h = _host("https://" + m.group(1))
        if h:
            found.append(h)
    # soft cues (not hosts) for evidence-quality notes
    return list(dict.fromkeys(found))


def _classify_divergence(prod: dict, rerun: dict, cmp: dict) -> str:
    """Label divergence as improvement / regression / noise / agree."""
    if rerun.get("error"):
        return "error"
    if cmp.get("stable_all_match"):
        return "agree"
    rating_cell = (cmp.get("stable") or {}).get("sse_rating") or {}
    is_sse_cell = (cmp.get("stable") or {}).get("is_sse") or {}
    notes: list[str] = []

    # Inconsistent prod rating vs is_sse → re-run fixing consistency = improvement
    prod_rating = prod.get("sse_rating")
    prod_is_sse = prod.get("is_sse")
    expected_is_sse = prod_rating in ("strong_yes", "weak_yes")
    prod_inconsistent = (
        prod_is_sse is not None
        and expected_is_sse is not None
        and bool(prod_is_sse) != bool(expected_is_sse)
    )

    if not rating_cell.get("match"):
        pr, rr = rating_cell.get("prod"), rating_cell.get("rerun")
        # strong_yes/weak_yes both Yes-side; no is No-side
        def side(r: Any) -> str:
            if r in ("strong_yes", "weak_yes"):
                return "yes"
            if r == "no":
                return "no"
            return "other"

        prod_reason = (
            ((prod.get("sse_details") or {}).get("reasoning") or "")
        ).lower()
        rerun_reason = (rerun.get("reasoning") or "").lower()
        for_profit_cues = ("for-profit", "for profit", "commercial", "private")

        if side(pr) == side(rr):
            notes.append("noise_within_yes_band")
        elif side(rr) == "yes" and side(pr) == "no":
            notes.append("possible_improvement_or_liberal")
        elif side(rr) == "no" and side(pr) == "yes":
            # Stricter for-profit gate vs old soft weak_yes → often improvement
            if any(c in prod_reason for c in for_profit_cues) or any(
                c in rerun_reason for c in for_profit_cues
            ):
                notes.append("improvement_stricter_for_profit")
            else:
                notes.append("possible_regression_or_stricter")
        else:
            notes.append("rating_drift")

    if not is_sse_cell.get("match"):
        if prod_inconsistent and is_sse_cell.get("rerun") == expected_is_sse:
            notes.append("improvement_fixed_prod_is_sse_inconsistency")
        else:
            notes.append("is_sse_drift")

    if not notes:
        return "noise"
    if any("improvement_stricter_for_profit" in n for n in notes):
        return "improvement_stricter_for_profit"
    if any(n.startswith("improvement") for n in notes) and not any(
        "regression" in n for n in notes
    ):
        return "improvement"
    if any("regression" in n for n in notes):
        return "regression"
    if any("noise" in n for n in notes):
        return "noise"
    return "divergence"


def _diff_notes(prod: dict, rerun: dict, cmp: dict, label: str) -> list[str]:
    notes: list[str] = []
    if rerun.get("error"):
        notes.append(f"Re-run failed: {rerun['error']}")
        return notes
    notes.append(f"Divergence label: **{label}**")
    for f, cell in (cmp.get("stable") or {}).items():
        if not cell.get("match"):
            notes.append(
                f"Structural drift on `{f}`: prod={cell.get('prod')} → "
                f"rerun={cell.get('rerun')}"
            )
    conf = (cmp.get("narrative") or {}).get("confidence") or {}
    if conf.get("abs_diff") is not None and conf["abs_diff"] >= 0.15:
        notes.append(f"Confidence shifted by {conf['abs_diff']:.2f}")
    reason_cell = (cmp.get("narrative") or {}).get("reasoning") or {}
    if not reason_cell.get("match"):
        notes.append("Reasoning text drifted (expected for narrative fields)")
    mh = (cmp.get("narrative") or {}).get("must_haves_met") or {}
    if mh.get("prod_only") or mh.get("rerun_only"):
        notes.append(
            f"must_haves set drift (prod_only={len(mh.get('prod_only') or [])}, "
            f"rerun_only={len(mh.get('rerun_only') or [])})"
        )
    hosts = rerun.get("tavily_hosts") or []
    if hosts:
        notes.append(f"Tavily hosts: {', '.join(hosts)}")
    old_hosts = _cite_hosts_from_reasoning(
        (prod.get("sse_details") or {}).get("reasoning")
    )
    if old_hosts:
        notes.append(f"Hosts cited in old reasoning: {', '.join(old_hosts)}")
    else:
        notes.append(
            "Old reasoning cited no URLs (typical of Gemini grounding prose "
            "that paraphrases search without linking)."
        )
    if cmp.get("stable_all_match"):
        notes.append("Structural fields matched")
    bq = prod.get("baseline_quality") or {}
    notes.append(
        f"Baseline quality={bq.get('quality')} score={bq.get('score')} "
        f"signals={bq.get('signals')}"
    )
    return notes


