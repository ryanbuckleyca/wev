def _parse_details(raw: Any) -> dict:
    if isinstance(raw, dict):
        return raw
    if isinstance(raw, str) and raw.strip():
        try:
            parsed = json.loads(raw)
            return parsed if isinstance(parsed, dict) else {}
        except json.JSONDecodeError:
            return {"raw": raw}
    return {}


def _host(url: str) -> str | None:
    try:
        host = urlparse(url).netloc.lower()
    except Exception:
        return None
    if host.startswith("www."):
        host = host[4:]
    return host or None


def _baseline_quality(details: dict) -> dict[str, Any]:
    """Score how Gemini-grounded / non-placeholder a prod baseline looks."""
    reason = (details.get("reasoning") or "").strip()
    blob = json.dumps(details, default=str).lower()
    signals: list[str] = []
    score = 0

    if not reason or reason == PLACEHOLDER_REASONING:
        return {
            "score": -10,
            "signals": ["placeholder_or_empty_reasoning"],
            "quality": "placeholder",
        }

    score += 2
    signals.append("real_reasoning")
    if len(reason) >= 120:
        score += 1
        signals.append("long_reasoning")
    if details.get("must_haves_met"):
        score += 2
        signals.append("has_must_haves")
    if details.get("nice_to_haves_met"):
        score += 1
        signals.append("has_nice_to_haves")
    if details.get("classified_at"):
        score += 1
        signals.append("has_classified_at")
    if details.get("provider") or details.get("model"):
        score += 2
        signals.append("has_provider_or_model")
    if "gemini" in blob:
        score += 3
        signals.append("gemini_in_details")
    if any(x in blob for x in ("google_search", "grounding", "grounded")):
        score += 3
        signals.append("grounding_flag_in_details")
    if any(
        x in reason.lower()
        for x in (
            "registered",
            "nonprofit",
            "non-profit",
            "charity",
            "mission",
            "for-profit",
            "governance",
            "website",
        )
    ):
        score += 1
        signals.append("evidencey_reasoning")

    quality = "strong" if score >= 6 else ("moderate" if score >= 3 else "weak")
    return {"score": score, "signals": signals, "quality": quality}


def fetch_gemini_grounded_jobs(limit: int = 5) -> tuple[list[dict], dict[str, Any]]:
    """Prefer jobs that look like older Gemini-grounded classifies."""
    cutoff = (datetime.now(timezone.utc) - timedelta(days=7)).isoformat()
    meta: dict[str, Any] = {
        "last_7d_count": 0,
        "sampled": 0,
        "baseline_note": "",
    }

    base = (
        supabase.table("jobs")
        .select(JOB_SELECT)
        .not_.is_("sse_rating", "null")
        .not_.is_("is_sse", "null")
    )
    recent = (
        base.gte("scraped_at", cutoff)
        .order("scraped_at", desc=True)
        .limit(100)
        .execute()
        .data
        or []
    )
    meta["last_7d_count"] = len(recent)

    rows = recent
    if not rows:
        logger.warning("No rated jobs in last 7d — scanning newest rated jobs")
        rows = (
            supabase.table("jobs")
            .select(JOB_SELECT)
            .not_.is_("sse_rating", "null")
            .not_.is_("is_sse", "null")
            .order("scraped_at", desc=True)
            .limit(200)
            .execute()
            .data
            or []
        )

    meta["sampled"] = len(rows)
    scored: list[tuple[int, dict, dict]] = []
    for row in rows:
        desc = (row.get("description") or "").strip()
        if len(desc) < 80:
            continue
        details = _parse_details(row.get("sse_details"))
        row = {**row, "sse_details": details}
        bq = _baseline_quality(details)
        scored.append((bq["score"], row, bq))

    scored.sort(key=lambda t: (-t[0], t[1].get("scraped_at") or ""))
    strong = [t for t in scored if t[2]["quality"] in ("strong", "moderate")]
    pool = strong if strong else scored

    # Prefer variety of ratings/orgs among best baselines
    picked: list[dict] = []
    picked_meta: list[dict] = []
    seen_orgs: set[str] = set()
    seen_ratings: set[str] = set()
    for score, row, bq in pool:
        if len(picked) >= limit:
            break
        org = (row.get("organization") or "").strip().lower()
        rating = (row.get("sse_rating") or "").strip().lower()
        # Prefer new org + rating diversity early
        if org in seen_orgs and len(picked) < limit - 1:
            continue
        if rating in seen_ratings and len(picked) < max(2, limit - 2) and len(pool) > limit:
            # keep some rating mix when enough candidates
            continue
        picked.append(row)
        picked_meta.append({"score": score, **bq})
        seen_orgs.add(org)
        seen_ratings.add(rating)

    # Fill remaining if diversity filters left gaps
    if len(picked) < limit:
        for score, row, bq in pool:
            if len(picked) >= limit:
                break
            if any(p["id"] == row["id"] for p in picked):
                continue
            picked.append(row)
            picked_meta.append({"score": score, **bq})

    qualities = [m["quality"] for m in picked_meta]
    if not recent:
        meta["baseline_note"] = (
            "No rated jobs in last 7 days. Selected best available non-placeholder "
            f"baselines (qualities={qualities}). Job sse_details had no explicit "
            "provider/model/grounding flags; real structured reasoning + must_haves "
            "used as proxy for older Gemini-grounded classifies."
        )
    else:
        meta["baseline_note"] = (
            f"Selected from last-7d pool; baseline qualities={qualities}."
        )
    meta["picked_baseline"] = [
        {
            "id": p["id"],
            "organization": p.get("organization"),
            "sse_rating": p.get("sse_rating"),
            **m,
        }
        for p, m in zip(picked, picked_meta)
    ]
    return picked[:limit], meta


def _org_type_map(org_ids: list[Any]) -> dict[Any, dict]:
    ids = [i for i in org_ids if i is not None]
    if not ids:
        return {}
    rows = (
        supabase.table("organizations")
        .select("id,name,type,sse_rating,is_sse,sse_details")
        .in_("id", ids)
        .execute()
        .data
        or []
    )
    out: dict[Any, dict] = {}
    for r in rows:
        d = _parse_details(r.get("sse_details"))
        out[r["id"]] = {
            "id": r["id"],
            "name": r.get("name"),
            "type": r.get("type"),
            "sse_rating": r.get("sse_rating"),
            "is_sse": r.get("is_sse"),
            "reasoning_preview": ((d.get("reasoning") or "")[:200] or None),
        }
    return out


def classify_job_tavily_always(clf: SSEClassifier, job: dict) -> dict[str, Any]:
    """Classify with Tavily grounding always on; capture evidence hosts."""
    org_name = job.get("organization") or job.get("org_name") or "Unknown"
    job_title = job.get("job_title") or job.get("title") or "Unknown"
    location = job.get("location") or "Unknown"
    salary = job.get("wage") or job.get("salary") or "Not specified"
    description = (job.get("description") or "").strip()
    posted_date = str(job.get("date_posted") or datetime.now(timezone.utc).isoformat())
    listing_url = job.get("listing_url") or ""

    if not description:
        raise SSEClassificationError("Job description required for parity re-run")

    prompt = get_sse_classification_prompt(
        org_name=org_name,
        job_title=job_title,
        location=location,
        salary=salary,
        job_description=description,
        posted_date=posted_date,
    )

    search_terms = f'"{org_name}"'
    if location and location != "Unknown":
        search_terms += f' "{location}"'
    search_query = f"{search_terms} official website mission governance"
    require_terms = entity_require_terms(org_name) or None

    # Capture the same evidence pack the chain will see (for report hosts).
    evidence = fetch_tavily_evidence(
        search_query,
        require_terms=require_terms,
    )
    tavily_urls = list(evidence.urls or [])
    tavily_hosts = sorted({h for u in tavily_urls if (h := _host(u))})

    t0 = time.perf_counter()
    last_error = ""
    for attempt in range(2):
        try:
            response_text = clf._call_provider_with_retry(
                provider=clf.provider,
                prompt=prompt,
                system=(
                    "You are an expert at analyzing job postings for Solidarity "
                    "Economy alignment. Score the role from the posting body. "
                    "Do not invent a different employer from search. Supporting "
                    "web evidence (Tavily) may clarify employer identity / mission "
                    "but must not override clear posting facts."
                ),
                task="sse",
                search_query=search_query,
                retries=0,
                require_terms=require_terms,
                use_grounding=True,  # tavily-always
            )
        except SSEClassificationError as exc:
            last_error = str(exc)
            logger.warning("provider error attempt %d/2: %s", attempt + 1, last_error)
            if "429" in last_error or "quota" in last_error.lower():
                time.sleep(8)
            continue

        parsed, parse_error = clf._safe_parse_sse_response(
            response_text, job_title, org_name
        )
        if parsed is not None:
            rating = parsed["rating"]
            provider_name = getattr(clf.provider, "current_model", None) or getattr(
                clf.provider, "_last_successful", None
            )
            return {
                "sse_rating": rating,
                "is_sse": rating in ("strong_yes", "weak_yes"),
                "type": None,  # job classify path does not emit org type
                "confidence": parsed.get("confidence"),
                "reasoning": parsed.get("reasoning"),
                "must_haves_met": parsed.get("must_haves_met") or [],
                "nice_to_haves_met": parsed.get("nice_to_haves_met") or [],
                "flags": parsed.get("flags") or [],
                "classified_at": parsed.get("classified_at"),
                "provider": provider_name,
                "listing_url": listing_url,
                "search_query": search_query,
                "tavily_always": True,
                "tavily_urls": tavily_urls,
                "tavily_hosts": tavily_hosts,
                "tavily_evidence_chars": len(evidence.text or ""),
                "elapsed_s": round(time.perf_counter() - t0, 2),
                "error": None,
            }
        last_error = parse_error or "parse error"
        logger.warning("parse error attempt %d/2: %s", attempt + 1, last_error)

    return {
        "error": last_error or "classification failed",
        "elapsed_s": round(time.perf_counter() - t0, 2),
        "tavily_always": True,
        "tavily_urls": tavily_urls,
        "tavily_hosts": tavily_hosts,
        "tavily_evidence_chars": len(evidence.text or ""),
        "type": None,
    }


